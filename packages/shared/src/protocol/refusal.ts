    // movement
    'noSuchSector',
    'noPath',
    'targetNotAdjacent',
    'hostileDronesPresent',
    'noHyperspaceDrive',
    'noDroneSignal',
    // trading
    'portDoesNotTrade',
    'insufficientPortStock',
