    'noShip',
    'docked',
    'notDocked',
    'alreadyDocked',
    'onPlanet',
    'notOnPlanet',
    'notAtStarbase',
    'notAtClass0OrStarbase',
    'noStarbaseHere',
    'noPortHere',
    'restrictedSector',
    'inEncounter',
    'noEncounter',
    'noPreviousSector',
    'shipNameRequired',
    // resources
    'insufficientTurns',
    'insufficientCredits',
    'insufficientFuel',
    'insufficientHolds',
    'insufficientCargo',
    'insufficientMaterials',
    'insufficientTreasury',
    'insufficientPlanetFuel',
    'notEnoughDrones',
    'insufficientShields',
    'insufficientMines',
    'minesAtCapacity',
    'noDronesToLaunch',
    'noColonistsOnShip',
    'dronesAtCapacity',
    'shipDronesAtMax',
